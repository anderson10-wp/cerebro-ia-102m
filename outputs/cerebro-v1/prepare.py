"""Bounded CPU preparation, original tokenizer and document-disjoint splits."""
import argparse, gzip, hashlib, json, os, random, re, time
from pathlib import Path
import numpy as np
from huggingface_hub import HfApi, hf_hub_download
from tokenizers import Tokenizer, models, pre_tokenizers, decoders, trainers

LICENSES = {'mit', 'apache-2.0', 'bsd-2-clause', 'bsd-3-clause', 'isc', 'unlicense', 'cc0-1.0'}
SEED = 20261003

def fingerprint(text):
    return hashlib.blake2b(re.sub(r'\s+', ' ', text).strip().encode(), digest_size=16).digest()

def split_for(digest):
    bucket = int.from_bytes(digest[:8], 'big') % 1000
    return 'validation' if bucket < 5 else 'audit' if bucket < 10 else 'train'

def filtered(row, spec, domain):
    if domain == 'code' and (row.get('license', '').lower() not in LICENSES or row.get('autogenerated', False)):
        return None
    text = row.get(spec['field'], '')
    if not isinstance(text, str) or not 384 <= len(text) <= 120000:
        return None
    if domain == 'pt' and row.get('language_score', 1.0) < 0.9:
        return None
    if '\x00' in text or '-----BEGIN PRIVATE KEY' in text or '-----BEGIN RSA PRIVATE KEY' in text:
        return None
    return text

def source_files(spec):
    paths = [f for f in HfApi().list_repo_files(spec['repo'], repo_type='dataset', revision=spec['revision'])
             if f.startswith(spec['prefix']) and f.endswith(('.parquet', '.json.gz'))]
    random.Random(SEED).shuffle(paths)
    if not paths:
        raise RuntimeError('No source files: ' + spec['repo'])
    return paths

def rows(spec, paths):
    for name in paths:
        print(json.dumps({'event': 'download', 'repo': spec['repo'], 'file': name}), flush=True)
        path = hf_hub_download(spec['repo'], filename=name, repo_type='dataset', revision=spec['revision'])
        if name.endswith('.parquet'):
            import pyarrow.parquet as pq
            for batch in pq.ParquetFile(path).iter_batches(batch_size=256):
                yield from batch.to_pylist()
        else:
            with gzip.open(path, 'rt', encoding='utf-8') as handle:
                for line in handle:
                    yield json.loads(line)

def sha256_file(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        while chunk := f.read(8 * 1024 * 1024):
            h.update(chunk)
    return h.hexdigest()

def main():
    args = argparse.ArgumentParser()
    args.add_argument('--out', default='/kaggle/working/corpus')
    args.add_argument('--tokens', type=int, default=2_000_000_000)
    args.add_argument('--vocab', type=int, default=32768)
    cfg = args.parse_args()
    root = Path(cfg.out); root.mkdir(parents=True, exist_ok=True)
    sources = json.loads(Path(__file__).with_name('sources.json').read_text())
    paths = {key: source_files(spec) for key, spec in sources.items()}
    sample_path = root / 'tokenizer-sample.txt'
    with sample_path.open('w', encoding='utf-8') as sample:
        for domain, spec in sources.items():
            size, target = 0, int(80_000_000 * spec['weight'])
            for row in rows(spec, paths[domain]):
                text = filtered(row, spec, domain)
                if text is None or split_for(fingerprint(text)) != 'train':
                    continue
                sample.write(text + '\n'); size += len(text.encode())
                if size >= target:
                    break
    tok = Tokenizer(models.BPE(unk_token='<|unk|>'))
    tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    tok.decoder = decoders.ByteLevel()
    specials = ['<|pad|>', '<|unk|>', '<|eos|>', '<|user|>', '<|assistant|>', '<|system|>', '<|tool|>']
    trainer = trainers.BpeTrainer(vocab_size=cfg.vocab, min_frequency=3, special_tokens=specials,
                                 initial_alphabet=pre_tokenizers.ByteLevel.alphabet(), show_progress=True)
    tok.train([str(sample_path)], trainer)
    if tok.get_vocab_size() != cfg.vocab:
        raise RuntimeError(f'Unexpected vocabulary: {tok.get_vocab_size()}')
    tok.save(str(root / 'tokenizer.json'))
    sample_path.unlink()
    eos = tok.token_to_id('<|eos|>')
    counts, documents, hashes = {}, {}, {}
    seen = set()
    start = time.monotonic()
    with gzip.open(root / 'provenance.jsonl.gz', 'wt', encoding='utf-8') as provenance:
        for domain, spec in sources.items():
            target = int(cfg.tokens * spec['weight'])
            count = {split: 0 for split in ('train', 'validation', 'audit')}
            docs = {split: 0 for split in count}
            handles = {split: (root / f'{domain}-{split}.bin').open('wb') for split in count}
            pending = []
            def write_pending():
                if not pending:
                    return
                encoded = tok.encode_batch([item[0] for item in pending], add_special_tokens=False)
                for (_, digest, split, row), enc in zip(pending, encoded):
                    limit = target if split == 'train' else 1_000_000
                    if count[split] >= limit:
                        continue
                    ids = enc.ids + [eos]
                    ids = ids[:limit - count[split]]
                    np.asarray(ids, dtype=np.uint16).tofile(handles[split])
                    count[split] += len(ids); docs[split] += 1
                    provenance.write(json.dumps({'domain': domain, 'split': split, 'fingerprint': digest.hex(),
                                                 'url': row.get('url'), 'repo': row.get('repo_name'),
                                                 'path': row.get('path'), 'license': row.get('license', spec['license'])}) + '\n')
                pending.clear()
            try:
                for row in rows(spec, paths[domain]):
                    text = filtered(row, spec, domain)
                    if text is None:
                        continue
                    digest = fingerprint(text)
                    if digest in seen:
                        continue
                    seen.add(digest)
                    split = split_for(digest)
                    limit = target if split == 'train' else 1_000_000
                    if count[split] >= limit:
                        continue
                    pending.append((text, digest, split, row))
                    if len(pending) >= 64:
                        write_pending()
                    if count['train'] >= target and min(count['validation'], count['audit']) >= 200000:
                        break
                write_pending()
            finally:
                for handle in handles.values():
                    handle.close()
            if count['train'] < target or min(count['validation'], count['audit']) < 200000:
                raise RuntimeError(f'Insufficient data for {domain}: {count}')
            counts[domain], documents[domain] = count, docs
            for split in count:
                hashes[f'{domain}-{split}.bin'] = sha256_file(root / f'{domain}-{split}.bin')
            print(json.dumps({'event': 'domain_ready', 'domain': domain, 'tokens': count}), flush=True)
    hashes['tokenizer.json'] = sha256_file(root / 'tokenizer.json')
    manifest = {'seed': SEED, 'vocabulary': tok.get_vocab_size(), 'counts': counts, 'documents': documents,
                'sources': sources, 'sha256': hashes, 'preparation_seconds': time.monotonic() - start,
                'split_policy': 'normalized exact-text hash; validation buckets 0..4, audit 5..9; tokenizer trained on train only',
                'deduplication': 'normalized exact document text across all three corpora; no near-duplicate guarantee'}
    (root / 'manifest.json').write_text(json.dumps(manifest, indent=2))
    (root / 'sources.json').write_text(json.dumps(sources, indent=2))
    print(json.dumps({'event': 'corpus_ready', 'counts': counts}), flush=True)

if __name__ == '__main__':
    main()
